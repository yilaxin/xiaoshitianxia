const assert=require('node:assert/strict');
const fs=require('node:fs');
const path=require('node:path');
const {Storage,validate}=require('../app/desktop/storage.cjs');
const root=fs.mkdtempSync(path.join(__dirname,'../work/storage-check-'));
const store=new Storage(root);
const photo='data:image/jpeg;base64,'+fs.readFileSync(path.join(__dirname,'../assets/rice.jpg')).toString('base64');
const state={version:1,categories:['主食'],dishes:[{id:'d1',name:'炒饭',category:'主食',tags:['家常'],favorite:true,description:'验证照片保存',cover:photo,created:'2026-10-15'}],meals:[{id:'m1',date:'2026-10-15',type:'晚餐',title:'测试',place:'家里',maker:'自己',note:''}],records:[{id:'r1',dishId:'d1',mealId:'m1',date:'2026-10-15',note:'第一次',photos:[photo,photo]}],bookIndex:0,lastBackup:null};
assert.equal(store.load(),null);
store.save(state);
assert.deepEqual(store.load(),state);
assert.equal(fs.readdirSync(store.photoDir).length,1,'Duplicate photos should use one disk file');
const disk=JSON.parse(fs.readFileSync(store.file,'utf8'));
assert.match(disk.dishes[0].cover,/^local:[a-f0-9]{64}\.jpg$/);
assert.ok(fs.statSync(store.file).size<2000,'JSON should reference the photo rather than contain base64');
const before=fs.readFileSync(store.file,'utf8');
const bad=structuredClone(state);bad.records[0].dishId='missing';
assert.throws(()=>store.save(bad));
assert.equal(fs.readFileSync(store.file,'utf8'),before,'Invalid save must preserve existing state');
const traversal=structuredClone(state);traversal.dishes[0].cover='local:../../private';
assert.throws(()=>store.save(traversal));
assert.equal(fs.readFileSync(store.file,'utf8'),before);
const backupFile=path.join(store.backupDir,fs.readdirSync(store.backupDir)[0]);
const backup=JSON.parse(fs.readFileSync(backupFile,'utf8'));assert.equal(backup.app,'笑食天下');validate(backup.data);
assert.deepEqual(backup.data,state);
const deletion=store.beforeDelete();assert.ok(deletion.includes('删除前-'));assert.deepEqual(JSON.parse(fs.readFileSync(deletion,'utf8')).data,state);
const recovery=store.beforeRestore();assert.ok(fs.existsSync(recovery));
fs.writeFileSync(store.file,'broken-json');const brokenRecovery=store.beforeRestore();assert.equal(fs.readFileSync(brokenRecovery,'utf8'),'broken-json');
store.save(backup.data);assert.deepEqual(store.load(),state);
for(let n=1;n<=10;n++)fs.writeFileSync(path.join(store.backupDir,`2001-01-${String(n).padStart(2,'0')}.json`),'{}');
store.save(state);assert.equal(store.metadata().backupCount,7,'Keep seven daily backups');
console.log('PASS: photo roundtrip/dedup, atomic rejection, path validation, full backup restore, damaged-state preservation, seven-day retention');
const noPhoto=structuredClone(state);
noPhoto.dishes[0].cover='';noPhoto.records[0].photos=[];
store.save(noPhoto);assert.deepEqual(store.load(),noPhoto);
assert.deepEqual(store.portable(JSON.parse(fs.readFileSync(store.file,'utf8'))).data,noPhoto);
const noPhotoBackup=JSON.parse(fs.readFileSync(store.beforeRestore(),'utf8'));
store.save(noPhotoBackup.data);assert.deepEqual(store.load(),noPhoto);
const emptyEntry=structuredClone(noPhoto);emptyEntry.records[0].photos=[''];
assert.throws(()=>store.save(emptyEntry),'Empty photo arrays are allowed, invalid empty-string photo entries are not');
store.save(state);assert.deepEqual(store.load(),state,'A photo can be added later');
console.log('PASS: empty cover/photos roundtrip, portable backup/restore, later photo attachment, invalid photo entry rejection');
const ordered=structuredClone(state);ordered.tagOrder=['家常'];
store.save(ordered);assert.deepEqual(store.load().tagOrder,['家常']);
assert.deepEqual(store.portable(JSON.parse(fs.readFileSync(store.file,'utf8'))).data.tagOrder,['家常']);
for(const invalid of ['家常',['家常','家常'],[''],[null]]){
 const badOrder=structuredClone(ordered);badOrder.tagOrder=invalid;
 assert.throws(()=>store.save(badOrder));assert.deepEqual(store.load().tagOrder,['家常']);
}
console.log('PASS: optional tag order compatibility, persistence, portable backup and invalid-order rejection');
const tableState=structuredClone(state);
const tablePhoto='data:image/jpeg;base64,'+fs.readFileSync(path.join(__dirname,'../assets/pizza.jpg')).toString('base64');
tableState.meals[0].photos=[tablePhoto,tablePhoto];
store.save(tableState);assert.deepEqual(store.load(),tableState);
const tableDisk=JSON.parse(fs.readFileSync(store.file,'utf8'));
assert.match(tableDisk.meals[0].photos[0],/^local:/);
assert.equal(fs.readdirSync(store.photoDir).length,2,'Whole-table photos use the same deduplicated local photo library');
const tableBackup=store.portable(tableDisk);assert.deepEqual(tableBackup.data,tableState);
store.save(tableBackup.data);assert.deepEqual(store.load(),tableState);
for(const invalid of ['', [''], [null], Array(101).fill(tablePhoto), ['local:../../photo']]){
 const bad=structuredClone(tableState);bad.meals[0].photos=invalid;
 assert.throws(()=>store.save(bad));assert.deepEqual(store.load(),tableState,'Invalid table photos cannot replace saved data');
}
const emptyTable=structuredClone(tableState);emptyTable.meals[0].photos=[];store.save(emptyTable);assert.deepEqual(store.load(),emptyTable);
console.log('PASS: whole-table photo storage, deduplication, full backup/restore, empty photos, old meals and invalid-photo rejection');
